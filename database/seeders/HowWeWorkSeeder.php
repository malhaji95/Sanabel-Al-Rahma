    public function run(): void
    {
        $page = Page::firstWhere('slug', 'how-we-work');

        if (! $page || $page->sections()->exists()) {
            return;
        }

        $page->update([
            'title_ar' => 'كيف نعمل',
            'body_ar' => 'لا تبدأ المساعدة بزرّ التبرع، بل بمعرفة من يحتاجها فعلًا. '
                .'نعمل على مسار واضح: ندرس الحاجة، ونتحقق من البيانات، ونحدد الأولوية بعدل، '
                .'وننظم التبرع، ونراجع الصرف، ونتابع وصول المساعدة وأثرها، مع حماية كرامة العائلات وخصوصيتها.',
        ]);

        $order = 0;

        foreach ($this->sections() as $section) {
            PageSection::create($section + [
                'page_id' => $page->id,
                'sort_order' => $order += 10,
            ]);
        }
    }

