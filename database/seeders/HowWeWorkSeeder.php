 *
 * Their words, not a paraphrase: the three levels, the family's path, the
 * donor's path, the partnership panels, the reference cards and the
 * reference texts, in the order their model put them.
 *
 * Two things are deliberately not carried across. Their demonstration draws
 * itself in its own palette and its own typeface; this is drawn in the
 * identity, because a page inside the platform that looked like a different
 * site would be the separate HTML file they asked us not to deliver. And
 * their notes-to-the-developer panel is not content for a visitor — it is
 * answered in the reply to them instead.
 *
 * Seeded once. After that the rows are the association's, and this seeder
 * leaves a page that already has sections alone.
